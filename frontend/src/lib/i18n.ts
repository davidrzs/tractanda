// The label of a value; a value outside the vocabulary shows as it is.
export function label(lang: Lang, field: keyof Labels, value: string | number | null) {
  const names: Record<string, string> = labels[lang][field];
  return value === null ? copy[lang].noValue : (names[String(value)] ?? String(value));
}
